public class SwapData {
    public static void main(String[] args) {
        int Jeevika=100;
        int Gowri=200;
            System.out.println("Jeevika: "+Jeevika);
            System.out.println("Gowri :"+Gowri);
        int temp=Jeevika;
        Jeevika=Gowri;
        Gowri=temp;
        System.out.println("After swapping:");
        System.out.println("Jeevika: "+Jeevika);
        System.out.println("Gowri :"+Gowri);
    }
}
